// Modernization plan renderer (Requirements 3.5, 3.6). Pure: returns strings, writes nothing.
import { err, ok, type Result } from './result';
import type { AstMap, ContractMap, ProposedInvariant, Risk } from './types';

export interface Plan {
  readonly requirementsMd: string;
  readonly designMd: string;
  readonly tasksMd: string;
}

export type EarsPattern = 'Ubiquitous' | 'Event-driven' | 'State-driven' | 'Unwanted' | 'Optional';

/** The five EARS templates. Used by the renderer's self-check and by property P16. */
export const EARS_TEMPLATES: Record<EarsPattern, RegExp> = {
  Ubiquitous: /^The [^,]+ SHALL [^]+\.$/,
  'Event-driven': /^WHEN [^,]+, the [^,]+ SHALL [^]+\.$/,
  'State-driven': /^WHILE [^,]+, the [^,]+ SHALL [^]+\.$/,
  Unwanted: /^IF [^,]+, THEN the [^,]+ SHALL [^]+\.$/,
  Optional: /^WHERE [^,]+, the [^,]+ SHALL [^]+\.$/,
};

/** Matches one acceptance-criterion line: `1. **2.3 (Unwanted)** IF ..., THEN the ... SHALL ....` */
export const CRITERION_LINE = /^\d+\. \*\*\d+\.\d+ \(([A-Za-z-]+)\)\*\* (.+)$/;

interface Criterion {
  readonly pattern: EarsPattern;
  readonly text: string;
}

const code = (s: string) => `\`${s}\``;

function systemName(c: ContractMap): string {
  return `modernized ${code(c.name)} contract`;
}

function criteriaFor(c: ContractMap, risks: readonly Risk[], invariants: readonly ProposedInvariant[]): Criterion[] {
  const sys = systemName(c);
  const out: Criterion[] = [];
  const external = c.functions.filter((f) => f.kind === 'function' && (f.visibility === 'public' || f.visibility === 'external') && f.name !== '');
  const names = external.map((f) => code(f.name)).join(' and ');
  out.push({
    pattern: 'Ubiquitous',
    text: external.length > 0 ? `The ${sys} SHALL keep the external functions ${names} with their current parameters and return types.` : `The ${sys} SHALL keep the current external interface of ${code(c.name)}.`,
  });

  const mine = risks.filter((r) => r.contract === c.name);
  if (mine.some((r) => r.id === 'legacy-pragma')) {
    out.push({ pattern: 'Ubiquitous', text: `The ${sys} SHALL compile with Solidity 0.8.0 or later so that arithmetic overflow reverts.` });
  }
  for (const r of mine) {
    const where = r.function ? code(`${c.name}.${r.function}`) : code(c.name);
    if (r.id === 'tx-origin-auth') {
      out.push({ pattern: 'Unwanted', text: `IF ${where} checks the caller's identity, THEN the ${sys} SHALL use ${code('msg.sender')} and not ${code('tx.origin')}.` });
    } else if (r.id === 'unchecked-call') {
      out.push({ pattern: 'Unwanted', text: `IF a low-level call in ${where} returns false, THEN the ${sys} SHALL revert.` });
    } else if (r.id === 'call-before-write') {
      out.push({ pattern: 'Event-driven', text: `WHEN ${where} makes an external call, the ${sys} SHALL finish every state update before that call.` });
    }
  }
  for (const inv of invariants.filter((i) => i.contract === c.name)) {
    out.push({
      pattern: 'Ubiquitous',
      text: `The ${sys} SHALL keep the sum of ${code(inv.balances)} over all accounts equal to ${code(inv.supply)} after every state transition.`,
    });
    out.push({ pattern: 'State-driven', text: `WHILE Aegis Sentinel guards ${code(c.name)}, the ${sys} SHALL expose ${code('pause()')} to the Sentinel's derived address.` });
  }
  return out;
}

function riskTable(risks: readonly Risk[]): string {
  if (risks.length === 0) return '_No legacy risks detected._\n';
  const rows = risks.map((r) => `| ${r.id} | ${r.severity} | ${r.confidence} | ${r.contract}${r.function ? `.${r.function}` : ''} | ${r.loc.line}:${r.loc.column} | ${r.message} |`);
  return ['| Risk | Severity | Confidence | Where | Line:Col | Detail |', '|---|---|---|---|---|---|', ...rows, ''].join('\n');
}

/** Renders the three spec files. Fails (as a value) if any criterion would break EARS (3.6). */
export function renderPlan(map: AstMap, invariants: readonly ProposedInvariant[]): Result<Plan, string> {
  const reqs: string[] = [
    `# Requirements Document: Modernize ${map.source.name}`,
    '',
    '## Introduction',
    '',
    `Generated by Aegis Forge from ${code(map.source.name)} (sha256 ${map.source.sha256}). Every acceptance criterion uses EARS syntax.`,
    '',
    '## Detected legacy risks',
    '',
    riskTable(map.risks),
    '## Requirements',
    '',
  ];
  for (const [i, c] of map.contracts.entries()) {
    const n = i + 1;
    reqs.push(`### Requirement ${n}: Modernize ${code(c.name)}`, '', `**User Story:** As the owner of ${code(c.name)}, I want it upgraded without changing its behavior, so that existing users keep working and legacy risks are removed.`, '', '#### Acceptance Criteria', '');
    for (const [j, cr] of criteriaFor(c, map.risks, invariants).entries()) {
      if (!EARS_TEMPLATES[cr.pattern].test(cr.text)) return err(`criterion ${n}.${j + 1} does not match ${cr.pattern}: ${cr.text}`);
      reqs.push(`${j + 1}. **${n}.${j + 1} (${cr.pattern})** ${cr.text}`);
    }
    reqs.push('');
  }

  const design = [
    `# Design Document: Modernize ${map.source.name}`,
    '',
    '## Overview',
    '',
    `Upgrade ${map.contracts.map((c) => code(c.name)).join(', ') || 'the contracts'} to Solidity 0.8.x, keep the external interface, and fix each detected risk.`,
    '',
    '## Proposed invariants',
    '',
    invariants.length === 0
      ? '_No token-like contracts detected._'
      : invariants.map((i) => `- ${code(i.contract)}: ${code(`${i.id}`)} (Σ ${i.balances} = ${i.supply})`).join('\n'),
    '',
    '## Risk fixes',
    '',
    map.risks.length === 0 ? '_None._' : map.risks.map((r) => `- ${r.id} at ${r.contract}${r.function ? `.${r.function}` : ''} (${r.loc.line}:${r.loc.column})`).join('\n'),
    '',
  ];

  const tasks = ['# Implementation Plan', ''];
  map.contracts.forEach((c, i) => {
    tasks.push(`- [ ] ${i + 1}. Modernize ${code(c.name)}`);
    tasks.push(`  - [ ] ${i + 1}.1 Port to Solidity 0.8.x and keep the external interface`);
    const mine = map.risks.filter((r) => r.contract === c.name && r.id !== 'legacy-pragma');
    mine.forEach((r, j) => tasks.push(`  - [ ] ${i + 1}.${j + 2} Fix ${r.id} in ${r.function ?? c.name}`));
    if (invariants.some((inv) => inv.contract === c.name)) {
      tasks.push(`  - [ ] ${i + 1}.${mine.length + 2} Add Pausable and register ${code('balance-conservation')} with Aegis Sentinel`);
    }
  });
  tasks.push('');

  return ok({ requirementsMd: `${reqs.join('\n')}\n`.replace(/\n{3,}/g, '\n\n'), designMd: design.join('\n'), tasksMd: tasks.join('\n') });
}
